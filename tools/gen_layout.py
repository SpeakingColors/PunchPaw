#!/usr/bin/env python3
"""Generates src/editor/Layout.h from docs/mockup/layout.json (made by tools/dump_layout.py from the approved
mockup). Every position, size, label and tooltip in the native editor comes from the mockup this way.
The mockup page has a preview rig under the knobs ("not part of the plugin"); the real window leaves it out,
so the body, meter column and footer are shortened by the rig height and moved up. Run from the repo root."""
import json

d = json.load(open('docs/mockup/layout.json'))
CUT = 70                                  # rig 68 px plus the 2 px of slack below it in the mockup
H = 640 - CUT

def sh(r, dy):                            # move a rect up when it sits below the knob section
    return [r[0], r[1] - dy, r[2], r[3]]

for k in ('cheekL', 'cheekR'): d[k][3] = H
d['body'][3] -= CUT
d['meters'][3] -= CUT
for k in ('foot', 'winsz', 'footL'): d[k] = sh(d[k], CUT)

def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
def f(v):
    t = '%g' % v
    if 'e' in t: t = '%.4f' % v
    return t + ('' if '.' in t else '.0') + 'f'
def rc(r): return '{ ' + ', '.join(f(v) for v in r) + ' }'
def num(s): return float(s.replace('px', ''))
ROLE = {'rgb(232, 233, 238)': 0, 'rgb(244, 245, 247)': 1, 'rgb(169, 173, 184)': 2}
COL = {'var(--g)': 0, 'var(--y)': 1, 'var(--o)': 2, 'var(--r)': 3, 'var(--b)': 4}
def font(t):
    if t['ff'] == 'mono': return 2
    return 1 if int(t['fw']) >= 700 else 0
def txt(t, role=None):
    sp = 0.0 if t['ls'] == 'normal' else num(t['ls'])
    r = ROLE.get(t['tc'], 1) if role is None else role
    return '{ %s, %s, %s, %d, %s, %s, %d, %s }' % (q(t['t']), rc(t['r']), f(num(t['fs'])), font(t), f(sp), 'true' if t['tt'] == 'uppercase' else 'false', r, q(t['tip']))

o = []
o.append('// GENERATED by tools/gen_layout.py from docs/mockup/layout.json. Do not edit by hand.')
o.append('#pragma once')
o.append('namespace layout {')
o.append('struct Rc { float x, y, w, h; };')
o.append('struct Led { float cx, cy; int color; };          // color: 0 green, 1 yellow, 2 orange, 3 red, 4 blue')
o.append('struct Hit { Rc r; const char* tip; const char* name; };')
o.append('// font: 0 regular, 1 bold, 2 mono. role: 0 panel title colour, 1 ink, 2 dim.')
o.append('struct Txt { const char* s; Rc r; float size; int font; float spacing; bool upper; int role; const char* tip; };')
o.append('constexpr int W = 1200, H = %d;' % H)
for k in ['cheekL', 'cheekR', 'hdr', 'sub', 'body', 'top', 'disp', 'knobs', 'meters', 'foot', 'footL', 'logo', 'name', 's87', 'pPrev', 'pName', 'pNext', 'pSave',
          'bBypass', 'bGuide', 'bSettings', 'bAbout', 'cvDial', 'cvCurve', 'cvShape', 'cvHist', 'cvIn', 'cvOut', 'pkIn', 'pkOut', 'winsz']:
    o.append('constexpr Rc %s = %s;' % (k, rc(d[k])))

top = d['topKids']
leds = [t for t in top if t['cls'].startswith('led') and not t['cls'].startswith('led-hit')]
hits = [t for t in top if t['cls'] == 'led-hit']
assert len(leds) == 22 and len(hits) == 7, (len(leds), len(hits))
def led(t): return '{ %s, %s, %d }' % (f(t['r'][0] + t['r'][2] / 2), f(t['r'][1] + t['r'][3] / 2), COL[t['color']])
def hit(t): return '{ %s, %s, %s }' % (rc(t['r']), q(t['tip']), q(t['aria']))
o.append('constexpr Led viewLeds[3] = { ' + ', '.join(led(t) for t in leds[0:3]) + ' };')
o.append('constexpr Led ladder[12] = { ' + ', '.join(led(t) for t in leds[3:15]) + ' };')
o.append('constexpr const char* ladderTips[12] = { ' + ', '.join(q(t['tip']) for t in leds[3:15]) + ' };')
o.append('constexpr Led timingLeds[2] = { ' + ', '.join(led(t) for t in leds[15:17]) + ' };')
o.append('constexpr Led kneeLeds[2] = { ' + ', '.join(led(t) for t in leds[17:19]) + ' };')
o.append('constexpr Led thrLeds[3] = { ' + ', '.join(led(t) for t in leds[19:22]) + ' };')
o.append('constexpr const char* thrTips[3] = { ' + ', '.join(q(t['tip']) for t in leds[19:22]) + ' };')
o.append('constexpr Hit viewHits[3] = { ' + ', '.join(hit(t) for t in hits[0:3]) + ' };')
o.append('constexpr Hit timingHits[2] = { ' + ', '.join(hit(t) for t in hits[3:5]) + ' };')
o.append('constexpr Hit kneeHits[2] = { ' + ', '.join(hit(t) for t in hits[5:7]) + ' };')
# static plate texts
plate = [t for t in top if t['cls'] in ('lbl', 'lnum', 'ltxt', 'note')]
o.append('constexpr Txt plateTexts[%d] = {\n    ' % len(plate) + ',\n    '.join(txt(t) for t in plate) + ' };')
o.append('constexpr int numPlateTexts = %d;' % len(plate))
rdt = [t for t in top if t['cls'] == 'rdt']
assert len(rdt) == 2
o.append('constexpr Txt autoRead[2] = { ' + ', '.join(txt(t) for t in rdt) + ' };')
autonotes = [t for t in plate if t['cls'] == 'note' and t['r'][1] < 200 and t['r'][0] == 600]
assert len(autonotes) == 2
o.append('constexpr int autoNoteFirst = %d;   // the two "program dependent" notes (shown in Auto only)' % plate.index(autonotes[0]))
# the dial's tip
o.append('constexpr const char* dialTip = %s;' % q(d['tips']['dial']))
# small manual knobs
sm = d['tmk']
assert len(sm) == 2
o.append('struct SmallKnob { const char* name; Rc cell, label, knob, val; Rc end0, end1; const char* e0; const char* e1; const char* tip; };')
cells = []
for nm, c in zip(('attack', 'release'), sm):
    cells.append('{ %s, %s, %s, %s, %s, %s, %s, %s, %s, %s }' % (q(nm), rc(c['cell']), rc(c['lab']['r']), rc(c['knob']['r']), rc(c['val']),
                 rc(c['ends'][0]['r']), rc(c['ends'][1]['r']), q(c['ends'][0]['t']), q(c['ends'][1]['t']), q(c['knob']['tip'])))
o.append('constexpr SmallKnob smallKnobs[2] = { ' + ',\n    '.join(cells) + ' };')
o.append('constexpr const char* smallLabel[2] = { %s, %s };' % (q(sm[0]['lab']['t']), q(sm[1]['lab']['t'])))
# big knobs
o.append('struct KnobCell { const char* name; const char* label; Rc labelR; Rc knob; Rc value; const char* tip; int nticks; const char* ticks[11]; };')
names = ['thr', 'ratio', 'out', 'hp', 'mix', 'ceil']
kt = d['knobTexts'][2:8]
cl = []
for n, c, ticks in zip(names, d['kcells'], kt):
    tk = ticks + [''] * (11 - len(ticks))
    cl.append('{ %s, %s, %s, %s, %s, %s, %d, { %s } }' % (q(n), q(c['lab']['t']), rc(c['lab']['r']), rc(c['knob']['r']), rc(c['val']), q(c['knob']['tip']), len(ticks), ', '.join(q(x) for x in tk)))
o.append('constexpr KnobCell cells[6] = { ' + ',\n    '.join(cl) + ' };')
o.append('constexpr Txt vdiv = %s;' % txt(d['vdiv']))
# sub strip
sp = d['subParts']
tags = [t for t in sp if t['c'].startswith('tg')]
assert len(tags) == 5, len(tags)
o.append('constexpr Txt subText = %s;' % txt(sp[0]))
o.append('constexpr Txt subBest = %s;' % txt(sp[1]))
o.append('constexpr Txt subTags[5] = { ' + ', '.join(txt(t) for t in tags) + ' };')
o.append('constexpr const char* subTip = %s;' % q(d['tips']['sub']))
# display captions
caps = d['caps']
o.append('constexpr Rc dispCaps[3] = { ' + ', '.join(rc(c['r']) for c in caps) + ' };')
o.append('constexpr const char* dispCapText[3] = { ' + ', '.join(q(c['t']) for c in caps) + ' };')
parts = caps[1]['parts']
o.append('constexpr Rc shapeParts[3] = { ' + ', '.join(rc(p['r']) for p in parts) + ' };   // in, out, gain reduction')
o.append('constexpr const char* shapePartText[3] = { ' + ', '.join(q(p['t']) for p in parts) + ' };')
o.append('constexpr const char* displayTips[3] = { %s, %s, %s };' % (q(d['tips']['curve']), q(d['tips']['shape']), q(d['tips']['hist'])))
o.append('constexpr Rc meterCaps[2] = { ' + ', '.join(rc(t['r']) for t in d['mcap']) + ' };')
o.append('constexpr const char* meterTips[4] = { %s, %s, %s, %s };' % (q(d['tips']['cvIn']), q(d['tips']['cvOut']), q(d['tips']['pkIn']), q(d['tips']['pkOut'])))
o.append('constexpr const char* headerTips[8] = { ' + ', '.join(q(d['tips'][k]) for k in ('pPrev', 'pName', 'pNext', 'pSave', 'bBypass', 'bGuide', 'bSettings', 'bAbout')) + ' };')
o.append('constexpr const char* cheekTip = %s;' % q(d['tips']['cheek']))
o.append('} // namespace layout')
open('src/editor/Layout.h', 'w').write('\n'.join(o) + '\n')
print('ok', len(plate), 'plate texts, H =', H)
